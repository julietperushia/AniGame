using System;
using System.Collections.Generic;
using UnityEngine;

/// <summary>
/// Index of every campaign card, grouped by location (LOC 1-100) and floor.
/// Built by Tools > AniGame > Build Card Database and stored at Assets/Resources/CardDatabase.asset.
/// </summary>
[CreateAssetMenu(fileName = "CardDatabase", menuName = "AniGame/Card Database")]
public class CardDatabase : ScriptableObject
{
    [Serializable]
    public class LocationData
    {
        public int number;
        public string displayName;
        [Tooltip("Anime / series this location is themed on.")]
        public string anime;
        public List<Card> floors = new List<Card>();

        public int FloorCount => floors.Count;
        public string Title => string.IsNullOrEmpty(displayName) ? $"LOC {number}" : displayName;
        public string Subtitle => anime ?? "";
    }

    public List<LocationData> locations = new List<LocationData>();

    [Tooltip("Every talent asset (filled by the generator). Talent Orbs pick uniformly from this list.")]
    public List<Talent> talents = new List<Talent>();

    [Header("Generated by the Campaign Generator")]
    [Tooltip("Hash of the sheet this database was built from. Saves made with other data are reset.")]
    public string dataVersion;
    public string sourceFile;
    public string generatedAt;

    public int CardCount
    {
        get
        {
            int n = 0;
            foreach (var l in locations) n += l.floors.Count;
            return n;
        }
    }

    public int AnimeCount
    {
        get
        {
            var set = new HashSet<string>();
            foreach (var l in locations) if (!string.IsNullOrEmpty(l.anime)) set.Add(l.anime);
            return set.Count;
        }
    }

    static CardDatabase instance;
    Dictionary<string, Card> byKey;

    public static CardDatabase Instance
    {
        get
        {
            if (instance == null) instance = Resources.Load<CardDatabase>("CardDatabase");
            return instance;
        }
    }

    public int LocationCount => locations.Count;

    public LocationData GetLocation(int number)
    {
        if (number >= 1 && number <= locations.Count && locations[number - 1].number == number)
            return locations[number - 1];
        foreach (var l in locations) if (l.number == number) return l;
        return null;
    }

    public Card GetFloorCard(int location, int floor)
    {
        var loc = GetLocation(location);
        if (loc == null || floor < 1 || floor > loc.floors.Count) return null;
        return loc.floors[floor - 1];
    }

    public int FloorCount(int location)
    {
        var loc = GetLocation(location);
        return loc != null ? loc.floors.Count : 0;
    }

    public Card FindByKey(string key)
    {
        if (string.IsNullOrEmpty(key)) return null;
        if (byKey == null || byKey.Count == 0)
        {
            byKey = new Dictionary<string, Card>();
            foreach (var loc in locations)
                foreach (var c in loc.floors)
                    if (c != null && !byKey.ContainsKey(c.Key)) byKey[c.Key] = c;
        }
        byKey.TryGetValue(key, out Card card);
        return card;
    }

    Dictionary<CardRarity, List<Card>> byRarity;

    /// <summary>Talent by display name, asset name or class name (null if unknown).</summary>
    public Talent FindTalent(string name)
    {
        if (string.IsNullOrEmpty(name)) return null;
        string n = Normalize(name);
        foreach (var t in talents)
        {
            if (t == null) continue;
            if (Normalize(t.DisplayName) == n || Normalize(t.name) == n || Normalize(t.GetType().Name) == n) return t;
        }
        return null;
    }

    public Talent RandomTalent()
    {
        var valid = talents.FindAll(t => t != null);
        return valid.Count > 0 ? valid[UnityEngine.Random.Range(0, valid.Count)] : null;
    }

    /// <summary>A random character card whose sheet rarity matches (falls back to any card).</summary>
    public Card RandomCardOfRarity(CardRarity rarity)
    {
        if (byRarity == null)
        {
            byRarity = new Dictionary<CardRarity, List<Card>>();
            foreach (var loc in locations)
                foreach (var c in loc.floors)
                {
                    if (c == null) continue;
                    if (!byRarity.TryGetValue(c.rarity, out var list)) byRarity[c.rarity] = list = new List<Card>();
                    list.Add(c);
                }
        }
        if (byRarity.TryGetValue(rarity, out var pool) && pool.Count > 0) return pool[UnityEngine.Random.Range(0, pool.Count)];
        foreach (var kv in byRarity) if (kv.Value.Count > 0) return kv.Value[UnityEngine.Random.Range(0, kv.Value.Count)];
        return null;
    }

    static string Normalize(string s) => string.IsNullOrEmpty(s) ? "" : s.Replace(" ", "").Replace("_", "").Replace("-", "").ToLowerInvariant();

    void OnEnable()
    {
        byKey = null;
        byRarity = null;
    }
}
